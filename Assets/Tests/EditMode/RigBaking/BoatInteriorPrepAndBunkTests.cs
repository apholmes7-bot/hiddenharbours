    /// <summary>
    /// Prep stations and bunk geometry aboard (owner rulings 2026-11-14: bunks on boats are sleepable;
    /// a boat kitchenette cooks raw food in TWO steps, prepped at a prep station, then cooked on the
    /// cooktop). Runtime does not use these anchors yet. This fixture holds the data to the rulings
    /// before any runtime code depends on it.
    ///
    /// <para>The reader is checked on one small synthetic sidecar. Every committed interior def is
    /// then checked: each cooktop has a prep station on its own level within
    /// <see cref="BoatInteriorAnchor.PrepToCookMaxMetres"/>, each cook, prep and sleep reach point
    /// stands on walkable sole clear of every obstruction, and each bunk's mattress centre lies inside
    /// the berth box it names.</para>
    /// </summary>
    public class BoatInteriorPrepAndBunkTests
    {
        const string InteriorFolder = "Assets/_Project/Data/Boats/Interiors";

        /// <summary>
        /// Hulls whose interior comes from a rig-written <c>*.walk.json</c>, not from the kit. Those
        /// files are generated by <c>tools/rig-recipes/hull-walk.mjs</c> from each rig's
        /// <c>walk()</c> and must never be edited by hand. Their prep stations are therefore owed by
        /// the rig (a new interact entry in <c>walk()</c>, a regeneration and a re-stamp), and their
        /// bunk geometry by the walk importer, which can derive it from the
        /// <c>anchors.berths[]</c> (<c>poly</c>, <c>topZ</c>, <c>head</c>) those files already
        /// carry. Their levels hold no furniture boxes either (only holes), so the clearance checks
        /// below do not apply to them. A hull leaves this list in the PR that gives it the data.
        /// </summary>
        static readonly HashSet<string> OwedByTheRigWalk = new HashSet<string>(StringComparer.Ordinal)
        {
            "docs/art/rigs/gameplay/expeditionYacht120IsoRig.expedition_yacht_120.walk.json",
            "docs/art/rigs/gameplay/cruiserIsoRig.express_cruiser.walk.json",
            "docs/art/rigs/gameplay/goFastIsoRig.go_fast.walk.json",
            "docs/art/rigs/gameplay/motorYacht84IsoRig.motor_yacht_84.walk.json",
            "docs/art/rigs/gameplay/sideDraggerIsoRig.side_dragger.walk.json",
            "docs/art/rigs/gameplay/sportFisherIsoRig2.convertible.walk.json",
            "docs/art/rigs/gameplay/sportFisherIsoRig2.skybridge.walk.json",
            "docs/art/rigs/gameplay/sternTrawlerIsoRig.stern_trawler.walk.json",
            "docs/art/rigs/gameplay/sternTrawlerMk2IsoRig.stern_trawler_mk2.walk.json",
        };

        // ---- the reader, on one small sidecar -------------------------------------------------------

        const string InteriorRig = "// renderer\n";
        const string HullRig = "// loft\n";
        static byte[] Lf(string s) => Encoding.UTF8.GetBytes(s);

        static string Sidecar(string interact)
        {
            return "{\n" +
                "  \"schema\": \"hidden-harbours/boat-interior@1\",\n" +
                "  \"hull_stem\": \"testBoatIsoRig\",\n" +
                "  \"fits_hulls\": [\"testBoatIsoRig\"],\n" +
                "  \"interior_rig\": \"boatInteriorRig.js\",\n" +
                $"  \"derivedFromRigSha256\": \"{DeckSidecarReader.Sha256Hex(Lf(InteriorRig))}\",\n" +
                $"  \"hullRigSha256\": {{ \"testBoatIsoRig\": \"{DeckSidecarReader.Sha256Hex(Lf(HullRig))}\" }},\n" +
                "  \"frame\": { \"scale_px_per_m\": 32 },\n" +
                "  \"cell\": { \"w\": 480, \"h\": 420, \"pivot\": { \"x\": 240, \"y\": 232 } },\n" +
                "  \"motion\": { \"rides_hull_rock\": true },\n" +
                "  \"FOOTPRINT\": { \"house\": [[-1.3, 0.5], [1.3, 0.5], [1.3, 5.5], [-1.3, 5.5]] },\n" +
                "  \"WALKABLE\": {\n" +
                "    \"house_sole\": { \"z\": 0.7, \"polygon\": [[-1.2, 0.6], [1.2, 0.6], [1.2, 2.5], [-1.2, 2.5]],\n" +
                "      \"obstructions\": [ { \"id\": \"stove_counter\", \"footprint\": [[-1.2, 0.7], [-0.8, 0.7], [-0.8, 1.6], [-1.2, 1.6]],\n" +
                "        \"height_above_sole_m\": 0.92, \"treatment\": \"waist_block\" } ] },\n" +
                "    \"cuddy_sole\": { \"z\": 0.3, \"polygon\": [[-1.0, 2.5], [1.0, 2.5], [0.2, 5.5], [-0.2, 5.5]],\n" +
                "      \"obstructions\": [ { \"id\": \"v_berth\", \"footprint\": [[-0.9, 3.4], [0.9, 3.4], [0.4, 5.3], [-0.4, 5.3]],\n" +
                "        \"height_above_sole_m\": 0.45, \"treatment\": \"waist_block\" } ] }\n" +
                "  },\n" +
                "  \"THRESHOLD\": { \"id\": \"entry\", \"threshold_point\": [0, 0.5, 0.7], \"mechanism\": \"sliding\",\n" +
                "    \"slide\": { \"keep_clear\": [[-0.4, 0.5], [1.2, 0.5], [1.2, 0.3], [-0.4, 0.3]] } },\n" +
                "  \"INTERACT\": [" + interact + "]\n}";
        }

        const string Galley =
            "{ \"id\": \"galley\", \"action\": \"galley\", \"reach_point\": [-0.4, 1.15, 0.7] }";
        const string Prep =
            "{ \"id\": \"prep\", \"action\": \"prep\", \"reach_point\": [-0.4, 1.4, 0.7], \"counter\": \"stove_counter\" }";
        const string Bunk =
            "{ \"id\": \"bunk\", \"action\": \"sleep\", \"reach_point\": [0, 2.9, 0.3],\n" +
            "  \"bunk\": { \"level\": \"cuddy_sole\", \"obstruction\": \"v_berth\",\n" +
            "    \"mattress_centre\": [0, 4.35, 0.75], \"pillow_end\": [0, 3.4, 0.75] } }";

        static BoatInteriorRead Read(string interact) =>
            BoatInteriorSidecarReader.Read(Sidecar(interact), "test.interior.json", Lf(InteriorRig), Lf(HullRig));

        [Test]
        public void TheReaderCarriesThePrepStationAndTheBunkGeometry()
        {
            BoatInteriorRead read = Read(Galley + ",\n" + Prep + ",\n" + Bunk);
            Assert.IsTrue(read.Ok, string.Join(" | ", read.Errors));

            BoatInteriorAnchor galley = read.Anchors.Single(a => a.Id == "galley");
            Assert.AreEqual(BoatInteriorAnchor.ActionCook, galley.Action,
                            "a galley IS a cooktop: its verb bakes as cook, its id stays galley");
            Assert.IsFalse(galley.HasBunkGeometry);

            BoatInteriorAnchor prep = read.Anchors.Single(a => a.Id == "prep");
            Assert.AreEqual(BoatInteriorAnchor.ActionPrep, prep.Action);
            Assert.AreEqual(new Vector3(-0.4f, 1.4f, 0.7f), prep.ReachPoint);

            BoatInteriorAnchor bunk = read.Anchors.Single(a => a.Id == "bunk");
            Assert.IsTrue(bunk.HasBunkGeometry);
            Assert.AreEqual("cuddy_sole", bunk.BunkLevel);
            Assert.AreEqual("v_berth", bunk.BunkObstruction);
            Assert.AreEqual(new Vector3(0f, 4.35f, 0.75f), bunk.MattressCentre);
            Assert.AreEqual(new Vector3(0f, 3.4f, 0.75f), bunk.PillowEnd);
        }

        [Test]
        public void ASleepAnchorWithoutABunkBlockReadsAsNotGiven_AndSaysSo()
        {
            BoatInteriorRead read = Read("{ \"id\": \"bunk\", \"action\": \"sleep\", \"reach_point\": [0, 2.9, 0.3] }");
            Assert.IsTrue(read.Ok, string.Join(" | ", read.Errors));
            BoatInteriorAnchor bunk = read.Anchors.Single();
            Assert.IsFalse(bunk.HasBunkGeometry);
            Assert.AreEqual("", bunk.BunkLevel);
            Assert.AreEqual(Vector3.zero, bunk.MattressCentre);
            Assert.IsTrue(read.Notes.Any(n => n.Contains("'bunk'") && n.Contains("pillow")), string.Join(" | ", read.Notes));
        }

        [Test]
        public void AHalfStatedBunkIsRefused()
        {
            BoatInteriorRead read = Read("{ \"id\": \"bunk\", \"action\": \"sleep\", \"reach_point\": [0, 2.9, 0.3],\n" +
                                         "  \"bunk\": { \"level\": \"cuddy_sole\", \"mattress_centre\": [0, 4.35, 0.75] } }");
            Assert.IsFalse(read.Ok);
            Assert.IsTrue(read.Errors.Any(e => e.Contains("pillow_end")), string.Join(" | ", read.Errors));
        }

        [Test]
        public void ABunkOnALevelTheInteriorDoesNotHaveIsRefused()
        {
            BoatInteriorRead read = Read(Bunk.Replace("\"level\": \"cuddy_sole\"", "\"level\": \"forepeak\""));
            Assert.IsFalse(read.Ok);
            Assert.IsTrue(read.Errors.Any(e => e.Contains("forepeak")), string.Join(" | ", read.Errors));
        }

        // ---- every committed def ------------------------------------------------------------------

        static List<BoatInteriorDef> CommittedDefs()
        {
            var defs = new List<BoatInteriorDef>();
            foreach (string guid in AssetDatabase.FindAssets("t:BoatInteriorDef", new[] { InteriorFolder }))
            {
                var def = AssetDatabase.LoadAssetAtPath<BoatInteriorDef>(AssetDatabase.GUIDToAssetPath(guid));
                if (def != null) defs.Add(def);
            }
            defs.Sort((a, b) => string.CompareOrdinal(a.Id, b.Id));
            return defs;
        }

        static bool Owed(BoatInteriorDef def) => OwedByTheRigWalk.Contains(def.SourceSidecar ?? "");

        static IEnumerable<BoatInteriorAnchor> Anchors(BoatInteriorDef def, string action) =>
            (def.Anchors ?? Array.Empty<BoatInteriorAnchor>()).Where(a => a != null && a.Action == action);

        /// <summary>The levels a reach point can be standing on: those whose sole is at its height.</summary>
        static IEnumerable<BoatInteriorLevel> LevelsAt(BoatInteriorDef def, float z) =>
            def.Levels.Where(l => l != null && Mathf.Abs(l.SoleZMeters - z) <= def.FloorTolerance);

        static bool Inside(Vector2[] polygon, Vector2 p)
        {
            if (polygon == null || polygon.Length < 3) return false;
            bool c = false;
            for (int i = 0, j = polygon.Length - 1; i < polygon.Length; j = i++)
            {
                Vector2 a = polygon[i], b = polygon[j];
                if ((a.y > p.y) != (b.y > p.y) && p.x < (b.x - a.x) * (p.y - a.y) / (b.y - a.y) + a.x) c = !c;
            }
            return c;
        }

        static bool StandsClear(BoatInteriorLevel level, Vector2 p) =>
            Inside(level.Outline, p) &&
            !(level.Obstructions ?? Array.Empty<BoatInteriorObstruction>()).Any(o => o != null && Inside(o.Footprint, p));

        [Test]
        public void TheCommittedDefsAreThere()
        {
            List<BoatInteriorDef> defs = CommittedDefs();
            Assert.Greater(defs.Count, 0, $"no BoatInteriorDef under {InteriorFolder}");
            Assert.Greater(defs.Count(d => !Owed(d)), 0, "no kit-built def to hold to the rulings");
        }

        [Test]
        public void EveryCooktopHasAPrepStationBesideItOnItsOwnLevel()
        {
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
            {
                if (Owed(def)) continue;
                BoatInteriorAnchor[] preps = Anchors(def, BoatInteriorAnchor.ActionPrep).ToArray();
                foreach (BoatInteriorAnchor cook in Anchors(def, BoatInteriorAnchor.ActionCook))
                {
                    bool served = preps.Any(p =>
                        Mathf.Abs(p.ReachPoint.z - cook.ReachPoint.z) <= def.FloorTolerance &&
                        Vector2.Distance(p.ReachPoint, cook.ReachPoint) <= BoatInteriorAnchor.PrepToCookMaxMetres);
                    if (!served)
                        faults.Add($"{def.Id}: cook anchor '{cook.Id}' has no prep anchor on its level within " +
                                   $"{BoatInteriorAnchor.PrepToCookMaxMetres} m");
                }
            }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }

        [Test]
        public void EveryCookPrepAndSleepReachStandsOnTheSoleClearOfObstructions()
        {
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
            {
                if (Owed(def)) continue;
                foreach (string action in new[] { BoatInteriorAnchor.ActionCook, BoatInteriorAnchor.ActionPrep,
                                                  BoatInteriorAnchor.ActionSleep })
                    foreach (BoatInteriorAnchor a in Anchors(def, action))
                    {
                        // Several planes can share a height (the packet's weather deck and her
                        // deckhouse sole); standing clear on any one of them is standing.
                        if (!LevelsAt(def, a.ReachPoint.z).Any(l => StandsClear(l, a.ReachPoint)))
                            faults.Add($"{def.Id}: {action} anchor '{a.Id}' reach {a.ReachPoint} is not on a " +
                                       "walkable sole clear of every obstruction");
                    }
            }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }

        [Test]
        public void EveryBunkSaysWhereItsMattressIsAndTheMattressIsInItsBerth()
        {
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
                foreach (BoatInteriorAnchor a in Anchors(def, BoatInteriorAnchor.ActionSleep))
                {
                    if (!a.HasBunkGeometry)
                    {
                        if (!Owed(def)) faults.Add($"{def.Id}: sleep anchor '{a.Id}' gives no bunk geometry");
                        continue;
                    }
                    BoatInteriorLevel level = def.Level(a.BunkLevel);
                    BoatInteriorObstruction berth = level?.Obstructions?.FirstOrDefault(o => o != null && o.Id == a.BunkObstruction);
                    if (berth == null)
                    {
                        faults.Add($"{def.Id}: sleep anchor '{a.Id}' names berth '{a.BunkObstruction}' on " +
                                   $"'{a.BunkLevel}', which is not there");
                        continue;
                    }
                    if (!Inside(berth.Footprint, a.MattressCentre))
                        faults.Add($"{def.Id}: '{a.Id}' mattress centre {a.MattressCentre} is outside '{berth.Id}'");
                    float top = level.SoleZMeters + berth.HeightAboveSoleMeters;
                    if (Mathf.Abs(a.MattressCentre.z - top) > def.FloorTolerance)
                        faults.Add($"{def.Id}: '{a.Id}' mattress top z {a.MattressCentre.z} is not the berth top {top}");
                    if (((Vector2)(a.PillowEnd - a.MattressCentre)).sqrMagnitude < 1e-4f)
                        faults.Add($"{def.Id}: '{a.Id}' pillow end does not name an end");
                }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }

        // ---- two sleepers, two beds (owner ruling 2026-11-15) ----------------------------------------

        /// <summary>
        /// Every kit hull that sleeps anyone sleeps two, in two separate places: at least two sleep
        /// anchors with distinct ids, no two heads (pillow ends) nearer than
        /// <see cref="BoatInteriorAnchor.BunkMinSeparationMetres"/>, and no two reach points on one level
        /// nearer than that either, so the resolver's nearest-wins rule always tells them apart. The walk
        /// hulls are held by their own rigs (<see cref="OwedByTheRigWalk"/>).
        /// </summary>
        [Test]
        public void EveryKitHullThatSleepsSleepsTwoInSeparatePlaces()
        {
            float min = BoatInteriorAnchor.BunkMinSeparationMetres;
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
            {
                if (Owed(def)) continue;
                BoatInteriorAnchor[] sleeps = Anchors(def, BoatInteriorAnchor.ActionSleep).ToArray();
                if (sleeps.Length == 0) continue;
                if (sleeps.Length < 2)
                    faults.Add($"{def.Id}: sleeps one only ('{sleeps[0].Id}'); every hull that sleeps sleeps two");
                if (sleeps.Select(a => a.Id).Distinct(StringComparer.Ordinal).Count() != sleeps.Length)
                    faults.Add($"{def.Id}: two sleep anchors share an id");
                for (int i = 0; i < sleeps.Length; i++)
                    for (int j = i + 1; j < sleeps.Length; j++)
                    {
                        BoatInteriorAnchor a = sleeps[i], b = sleeps[j];
                        float heads = Vector3.Distance(a.PillowEnd, b.PillowEnd);
                        if (heads < min)
                            faults.Add($"{def.Id}: '{a.Id}' and '{b.Id}' put two heads {heads:0.000} m apart (< {min})");
                        bool oneLevel = Mathf.Abs(a.ReachPoint.z - b.ReachPoint.z) <= def.FloorTolerance;
                        float reaches = Vector2.Distance(a.ReachPoint, b.ReachPoint);
                        if (oneLevel && reaches < min)
                            faults.Add($"{def.Id}: '{a.Id}' and '{b.Id}' reach points are {reaches:0.000} m apart " +
                                       $"on one level (< {min})");
                        if (a.MattressCentre == b.MattressCentre)
                            faults.Add($"{def.Id}: '{a.Id}' and '{b.Id}' are one mattress");
                    }
            }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }

        /// <summary>Every kit bunk's mattress middle lies over its own level's walkable outline: the
        /// bed is inside the hull, never hung off the side.</summary>
        [Test]
        public void EveryKitBunksMattressLiesInsideItsLevel()
        {
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
            {
                if (Owed(def)) continue;
                foreach (BoatInteriorAnchor a in Anchors(def, BoatInteriorAnchor.ActionSleep))
                {
                    BoatInteriorLevel level = def.Level(a.BunkLevel);
                    if (level == null || !Inside(level.Outline, a.MattressCentre))
                        faults.Add($"{def.Id}: '{a.Id}' mattress {a.MattressCentre} is outside level '{a.BunkLevel}'");
                }
            }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }

        /// <summary>
        /// Each kit def's sleep anchors are its sidecar's, point for point. The builder carries the
        /// sidecar straight into the def; this holds the two together for a sleep anchor added to both
        /// at once, until the next <c>BoatInteriorDefBuilder.BuildAllCli</c> re-bake makes it moot.
        /// </summary>
        [Test]
        public void EveryKitDefsSleepAnchorsAreItsSidecars()
        {
            string root = System.IO.Directory.GetParent(Application.dataPath)!.FullName;
            const float tol = 1e-4f;
            var faults = new List<string>();
            foreach (BoatInteriorDef def in CommittedDefs())
            {
                if (Owed(def) || string.IsNullOrEmpty(def.SourceSidecar)) continue;
                string path = System.IO.Path.Combine(root, def.SourceSidecar);
                if (!System.IO.File.Exists(path)) { faults.Add($"{def.Id}: sidecar {def.SourceSidecar} missing"); continue; }
                object json = DeckSidecarJson.Parse(System.IO.File.ReadAllText(path));
                var fromSidecar = new Dictionary<string, object>(StringComparer.Ordinal);
                foreach (object e in DeckSidecarJson.AsArray(DeckSidecarJson.Member(json, "INTERACT")) ?? new List<object>())
                    if (DeckSidecarJson.String(DeckSidecarJson.Member(e, "action")) == BoatInteriorAnchor.ActionSleep)
                        fromSidecar[DeckSidecarJson.String(DeckSidecarJson.Member(e, "id")) ?? ""] = e;

                BoatInteriorAnchor[] sleeps = Anchors(def, BoatInteriorAnchor.ActionSleep).ToArray();
                if (sleeps.Length != fromSidecar.Count)
                    faults.Add($"{def.Id}: {sleeps.Length} sleep anchors baked, {fromSidecar.Count} in {def.SourceSidecar}");
                foreach (BoatInteriorAnchor a in sleeps)
                {
                    if (!fromSidecar.TryGetValue(a.Id, out object e)) { faults.Add($"{def.Id}: '{a.Id}' is not in its sidecar"); continue; }
                    object bunk = DeckSidecarJson.Member(e, "bunk");
                    void Same(string what, Vector3 baked, object raw)
                    {
                        List<object> p = DeckSidecarJson.AsArray(raw);
                        var v = p == null || p.Count < 3 ? new Vector3(float.NaN, float.NaN, float.NaN)
                            : new Vector3(DeckSidecarJson.Float(p[0]), DeckSidecarJson.Float(p[1]), DeckSidecarJson.Float(p[2]));
                        if (!(Vector3.Distance(baked, v) <= tol))
                            faults.Add($"{def.Id}: '{a.Id}' {what} baked {baked}, sidecar {v}");
                    }
                    Same("reach", a.ReachPoint, DeckSidecarJson.Member(e, "reach_point"));
                    Same("mattress", a.MattressCentre, DeckSidecarJson.Member(bunk, "mattress_centre"));
                    Same("pillow", a.PillowEnd, DeckSidecarJson.Member(bunk, "pillow_end"));
                    if (DeckSidecarJson.String(DeckSidecarJson.Member(bunk, "level")) != a.BunkLevel ||
                        DeckSidecarJson.String(DeckSidecarJson.Member(bunk, "obstruction")) != a.BunkObstruction)
                        faults.Add($"{def.Id}: '{a.Id}' berth level/obstruction differ from the sidecar");
                }
            }
            Assert.IsEmpty(faults, string.Join("\n", faults));
        }
    }
