        [Test]
        public void EveryPlanRoad_IsLaidByItsId_InItsPlanClassWidthAndSurface()
        {
            var plan = PlanRoads();
            var kit = KitClassTable();
            Assert.That(plan.Count, Is.EqualTo(19), "G3's plan draws nineteen roads; the network was built on that plan");
            for (int i = 0; i < plan.Count; i++)
            {
                var road = plan[i];
                string id = road.Get("id").Str("id"), from = $"roads[{i}]";
                var laid = Net.Routes.Where(r => r.From == from).ToList();
                Assert.That(laid, Is.Not.Empty, $"{from} ({id}) is not in the network");
                string cls = road.Get("cls").Str(id + ".cls");
                string surface = road.Get("surface") is { Kind: KeySceneImport.Json.Of.String } s ? s.Text : null;
                foreach (var r in laid)
                {
                    Assert.AreEqual(id, r.Id, $"{from} is laid under another id");
                    Assert.AreEqual(cls, r.Class, $"{r}: not the plan's class");
