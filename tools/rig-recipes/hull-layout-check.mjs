#!/usr/bin/env node
// THE HULL LAYOUT CHECKER (ADR 0048 §8; the spec is docs/art/hull-layout-spec.md).
//
//   node tools/rig-recipes/hull-layout-check.mjs                  # every hull; exit code 1 on any FAIL
//   node tools/rig-recipes/hull-layout-check.mjs --hull bowrider  # one hull
//
// Plain Node 16 or later: no dependencies, no network, nothing to install, and it writes nothing. It reads the rigs
// verbatim (in Node's own V8, as the writer does), the walks in docs/art/rigs/gameplay/, character rig 10.3 and the
// flotation table (FleetFlotationTableTests.cs). For each hull:
//   A. the rig through its global (§8 A): every face's tags in every state and every scheme; the room (it: true,
//      fitCheck <= 0.01 m); the leaf (doorFaces(t)); geometry() and its cutaway, each gate list complete (§6.4); the
//      paints (in every scheme every mat named, the hull <= 16 ramps, the room <= 24); the shade and the cell;
//   R. the pictures, by the rig's own renderer and by this file's raster of the faces: R1 the eight facings draw;
//      R2 qa.leakPx as the v3 sport fisher counts it (the uncut render against renderCut at each key that lifts
//      nothing and shows nothing, pixel for pixel); R3 the room inside the exterior's silhouette at the eight
//      facings; R4 the gate off, in true depth (db 0): no room face in front of the closed exterior by more than
//      0.01 m, the pixels it sees through the exterior's own 1-px cracks counted and reported; R5 renderCut drawing
//      nothing outside the uncut render, at every cut key and facing;
//   B. the walk (§8 B): every R row; the LF sha256 stamp; the file regenerated byte for byte by the writer
//      (tools/rig-recipes/hull-walk.mjs); and its tables held against the rig: DWL, cockpitZ, tags, house, the
//      areas, the climbs, every standing surface, interact, the anchors, cleats, washboards, rock, qa.
// Last, the fit to character rig 10.3, fixture by fixture, as the walk's qa.character has it: a table, not a check.
