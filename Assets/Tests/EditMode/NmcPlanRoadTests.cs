                    Assert.AreEqual(road.Get("width").Float(id + ".width"), r.Width, 1e-4f, $"{r}: not the plan's width");
                    Assert.AreEqual(surface ?? MiniJson.String(kit[cls], "surface"), SurfaceOf(r, kit), $"{r}: not the plan's surface");
                    Assert.That(r.Points.Length, Is.GreaterThanOrEqualTo(2), $"{r}: no line");
                }
            }
            // Route 91's town section north of the river bridge, and Shore Lane's turn, are laid from their own entries
            var town = Net.Routes.Single(r => r.From == "roads[0].sections[0]");
            Assert.AreEqual(("road.nmc_route_91_town", "town", 5.8f), (town.Id, town.Class, town.Width), "Route 91's town section");
