        sealed class Rig
        {
            public string Name;
            public float L, Track, FrontY, RearY, Inner, CoupleY, CabClear, Cap;
            public VehicleKingpin Pin;
            public Rig Trailer;
        }

        /// <summary>A number from a mesh Def's text: a top-level field, or one inside a block (four spaces in).</summary>
        static float Field(string text, string key, int indent = 2)
        {
            Match m = Regex.Match(text, "\n" + new string(' ', indent) + key + @": (-?[\d.eE+-]+)");
            Assert.IsTrue(m.Success, $"no {key}");
            return Num(m.Groups[1].Value);
        }

        static string Block(string text, string key)
        {
            int at = text.IndexOf("\n  " + key + ":\n", StringComparison.Ordinal);
            if (at < 0) return "";
            Match next = Regex.Match(text.Substring(at + key.Length + 4), "\n  [A-Za-z]");
            return text.Substring(at, key.Length + 4 + (next.Success ? next.Index : text.Length - at - key.Length - 4));
        }

        static Rig ReadRig(string name)
        {
            string t = File.ReadAllText(VehicleMeshes + name + "VehicleMesh.asset").Replace("\r\n", "\n");
            var rig = new Rig
            {
                Name = name, L = Field(t, "WheelbaseMeters"), Track = Field(t, "FrontTrackMeters"), FrontY = Field(t, "FrontAxleY"),
                RearY = Field(t, "RearAxleY"), Inner = Field(t, "MaxInnerSteerDegrees"),
            };
            string fifth = Block(t, "FifthWheel"), pin = Block(t, "Kingpin");
            if (fifth.Contains("\n    Published: 1"))
            {
                rig.CoupleY = Num(Regex.Match(fifth, @"CouplingPointLocal: \{x: (?:\S+), y: (-?[\d.eE+-]+)").Groups[1].Value);
                rig.CabClear = Field(fifth, "CabClearanceMeters", 4);
            }
            if (pin.Contains("\n    Published: 1"))
            {
                Match cp = Regex.Match(pin, @"CouplingPointLocal: \{x: (-?[\d.eE+-]+), y: (-?[\d.eE+-]+)");
                rig.Pin = new VehicleKingpin
                {
                    Published = true, CouplingPointLocal = new Vector3(Num(cp.Groups[1].Value), Num(cp.Groups[2].Value), 0f),
                    KingpinToAxleCentreMeters = Field(pin, "KingpinToAxleCentreMeters", 4),
                    NoseHalfWidthMeters = Field(pin, "NoseHalfWidthMeters", 4), KingpinSetMeters = Field(pin, "KingpinSetMeters", 4),
                };
            }
            return rig;
        }

        static Rig Pair(Rig tractor, Rig trailer)
        {
            var r = ReadRig(tractor.Name);
            r.Trailer = trailer;
            r.Cap = VehicleCouplingMath.JackknifeCapDegrees(trailer.Pin.NoseHalfWidthMeters, trailer.Pin.KingpinSetMeters, tractor.CabClear);
            return r;
        }

        sealed class Surface { public Vector2[] P; public float Band; public bool Flat; public Rect Near; }

        /// <summary>Every carriageway a wheel may stand on: the network's road classes and its corner flares out to
        /// their kit bands (a town street's gutter, a road's shoulder; a route's own bands replace its class's), and the
        /// decks.</summary>
        static List<Surface> Surfaces()
        {
            var kit = KitClassTable();
            var json = MiniJson.Parse(File.ReadAllText(NineMileCreekRoadNetwork.FilePath));
            var all = new List<Surface>();
            foreach (object o in MiniJson.List(json, "routes").Concat(MiniJson.List(json, "flares") ?? new List<object>()))
            {
                string cls = MiniJson.String(o, "cls");
                if (!RoadClasses.Contains(cls)) continue;
                float extra = 0f;
                if (MiniJson.Has(o, "bands"))
                {
                    foreach (object band in MiniJson.List(o, "bands"))
                    {
                        string role = MiniJson.String(band, "role");
                        if (role != "gutter" && role != "shoulder") break;
                        extra += MiniJson.Float(band, "w");
                    }
                }
                else
                    foreach (object band in MiniJson.List(kit[cls], "section").Skip(1))
                    {
                        string role = MiniJson.String(band, "role");
                        if (role != "gutter" && role != "shoulder") break;
                        extra += MiniJson.Float(band, "to_m") - MiniJson.Float(band, "from_m");
                    }
                var pts = MiniJson.List(o, "pts").Select(p => new Vector2((float)(double)((List<object>)p)[0], (float)(double)((List<object>)p)[1])).ToArray();
                all.Add(Make(pts, MiniJson.Float(o, "w") / 2f + extra, MiniJson.String(o, "ends") == "flat"));
            }
            foreach (var b in Net.Bridges) all.Add(Make(new[] { b.A, b.B }, b.Width / 2f, true));
            return all;
        }

        static Surface Make(Vector2[] pts, float band, bool flat)
        {
            float x0 = pts.Min(p => p.x), x1 = pts.Max(p => p.x), y0 = pts.Min(p => p.y), y1 = pts.Max(p => p.y);
            return new Surface { P = pts, Band = band, Flat = flat, Near = Rect.MinMaxRect(x0 - band - 1f, y0 - band - 1f, x1 + band + 1f, y1 + band + 1f) };
        }

        /// <summary>How far q stands outside a carriageway's band (negative inside); a flat end stops square.</summary>
        static float Outside(Surface st, Vector2 q)
        {
            float best = float.MaxValue;
            for (int i = 0; i < st.P.Length - 1; i++)
            {
                Vector2 a = st.P[i], d = st.P[i + 1] - a;
                float len = d.magnitude;
                if (len < 1e-6f) continue;
                Vector2 u = d / len, r = q - a;
                float s = Vector2.Dot(r, u), perp = Mathf.Abs(u.x * r.y - u.y * r.x), h = st.Band, o;
                bool flatA = st.Flat && i == 0, flatB = st.Flat && i == st.P.Length - 2;
                if (s < 0f) o = flatA ? (perp <= h ? -s : Mathf.Sqrt(s * s + (perp - h) * (perp - h))) : r.magnitude - h;
                else if (s > len) { float e = s - len; o = flatB ? (perp <= h ? e : Mathf.Sqrt(e * e + (perp - h) * (perp - h))) : (q - st.P[i + 1]).magnitude - h; }
                else o = perp - h;
                best = Mathf.Min(best, o);
            }
            return best;
        }

        static float WheelOut(List<Surface> surfaces, Vector2 q)
        {
            float best = float.MaxValue;
            foreach (var s in surfaces) if (s.Near.Contains(q)) best = Mathf.Min(best, Outside(s, q));
            return best;
        }

        static float[] Cum(Vector2[] p)
        {
            var c = new float[p.Length];
            for (int i = 1; i < p.Length; i++) c[i] = c[i - 1] + (p[i] - p[i - 1]).magnitude;
            return c;
        }

        static Vector2 At(Vector2[] p, float[] c, float s)
        {
            if (s <= 0f) return p[0];
            for (int i = 1; i < p.Length; i++)
                if (s <= c[i]) return Vector2.Lerp(p[i - 1], p[i], (s - c[i - 1]) / Mathf.Max(1e-6f, c[i] - c[i - 1]));
            return p[p.Length - 1];
        }

        /// <summary>The nearest point of the line within a few metres ahead of the last, so a loop never jumps a lap.</summary>
        static float ProjectNear(Vector2[] p, float[] c, Vector2 q, float hint)
        {
            float best = float.MaxValue, bs = hint;
            for (int i = 0; i < p.Length - 1; i++)
            {
                if (c[i + 1] < hint - 6f || c[i] > hint + 12f) continue;
                Vector2 d = p[i + 1] - p[i];
                float len2 = d.sqrMagnitude, t = len2 < 1e-9f ? 0f : Mathf.Clamp01(Vector2.Dot(q - p[i], d) / len2);
                float dist = (q - (p[i] + d * t)).sqrMagnitude;
                if (dist < best) { best = dist; bs = c[i] + t * Mathf.Sqrt(len2); }
            }
            return Mathf.Max(bs, hint - 0.5f);
        }

        static Vector2[] Offset(Vector2[] p, float o)
        {
            if (o == 0f) return p;
            var r = new Vector2[p.Length];
            for (int i = 0; i < p.Length; i++)
            {
                Vector2 dPrev = (i > 0 ? p[i] - p[i - 1] : p[1] - p[0]).normalized, dNext = (i < p.Length - 1 ? p[i + 1] - p[i] : dPrev).normalized;
                Vector2 nPrev = new Vector2(-dPrev.y, dPrev.x), nNext = new Vector2(-dNext.y, dNext.x), m = nPrev + nNext;
                if (m.sqrMagnitude < 1e-6f) m = nPrev;
                m.Normalize();
                r[i] = p[i] + m * (o / Mathf.Max(Vector2.Dot(m, nNext), 0.5f));
            }
            return r;
        }

        static float Bearing(Vector2 d) => Mathf.Atan2(d.x, d.y) * Mathf.Rad2Deg;
        static Vector2 Local(float bearing, float x, float y) => VehicleCouplingMath.LocalOffsetToWorld(new Vector2(x, y), bearing);

        /// <summary>One drive of the line: the worst wheel past its band (metres), or +infinity when the driver lost
        /// the line or never reached its end. Wheels count between the line's end planes, after <paramref name="from"/>
        /// metres travelled.</summary>
        static float Drive(List<Surface> surfaces, Vector2[] line, Rig rig, float look, float offset, bool planes = true, float from = 0f)
        {
            Vector2[] path = Offset(line, offset);
            float[] c = Cum(path);
            float total = c[c.Length - 1];
            float kmax = VehicleSteeringMath.YawRateDegreesPerSecond(1f, 1f, rig.Inner, rig.L, rig.Track) * Mathf.Deg2Rad;
            float lost = Mathf.Max(3f, 0.6f / kmax + 1f);
            Vector2 a0 = line[0], u0 = (line[1] - line[0]).normalized, an = line[line.Length - 1], un = (line[line.Length - 1] - line[line.Length - 2]).normalized;
            Vector2 tail = (path[path.Length - 1] - path[path.Length - 2]).normalized, o = path[0], ot = Vector2.zero;
            float b = Bearing(path[1] - path[0]), bt = b, s = 0f, worst = -9f, travelled = 0f;
            if (rig.Trailer != null) ot = VehicleCouplingMath.BodyOriginFromKingpin(o + Local(b, 0f, rig.CoupleY), bt, rig.Trailer.Pin);
            bool InWindow(Vector2 q) => !planes || (Vector2.Dot(q - a0, u0) >= 0f && Vector2.Dot(q - an, un) <= 0f);
            void Wheels(Vector2 at, float bearing, Rig r, bool trailer)
            {
                float x = r.Track / 2f + TyreHalf;
                foreach (float y in trailer ? new[] { r.RearY } : new[] { r.FrontY, r.RearY })
                    foreach (float sx in new[] { -x, x })
                    {
                        Vector2 q = at + Local(bearing, sx, y);
                        if (InWindow(q)) worst = Mathf.Max(worst, WheelOut(surfaces, q));
                    }
            }
            for (int steps = 0, max = (int)(3f * total / Step) + 2000; steps < max; steps++)
            {
                s = ProjectNear(path, c, o, s);
                if (s >= total - 1e-3f) return worst;
                if ((o - At(path, c, s)).magnitude > lost) return float.PositiveInfinity;
                float ahead = s + look;
                Vector2 target = ahead <= total ? At(path, c, ahead) : path[path.Length - 1] + tail * (ahead - total);
                Vector2 d = target - o, nose = NavMath.DirectionFromBearing(b);
                float alpha = Mathf.Atan2(nose.x * d.y - nose.y * d.x, Vector2.Dot(nose, d));
                float k = Mathf.Clamp(2f * Mathf.Sin(alpha) / Mathf.Max(0.5f, d.magnitude), -kmax, kmax);
                o += NavMath.DirectionFromBearing(b - k * Step * 0.5f * Mathf.Rad2Deg) * Step;
                b -= k * Step * Mathf.Rad2Deg;
                if (rig.Trailer != null)
                    VehicleCouplingMath.FollowStep(bt, o + Local(b, 0f, rig.CoupleY), b, Step, rig.Cap, rig.Trailer.Pin, out bt, out ot);
                travelled += Step;
                if (travelled < from) continue;
                Wheels(o, b, rig, false);
                if (rig.Trailer != null) Wheels(ot, bt, rig.Trailer, true);
            }
            return float.PositiveInfinity;
        }

        /// <summary>The best of the drivers: the first that keeps every wheel within its band, or the least worst.</summary>
        static float BestDrive(List<Surface> surfaces, Vector2[] line, Rig rig)
        {
            float best = float.PositiveInfinity;
            foreach (float look in Lookaheads)
                foreach (float off in Offsets)
                {
                    best = Mathf.Min(best, Drive(surfaces, line, rig, look, off));
                    if (best <= WheelTol) return best;
                }
            return best;
        }

