                Assert.IsTrue(File.Exists(file) && File.Exists(file + ".meta"), $"{b.Id}: no prefab at {file}");
                string yaml = File.ReadAllText(file).Replace("\r\n", "\n");
                CollectionAssert.AreEqual(new[] { "1", "4", "114" },
                    Regex.Matches(yaml, @"\n--- !u!(\d+) &").Cast<Match>().Select(m => m.Groups[1].Value).ToArray(),
                    $"{b.Prefab}: a plain deck is a GameObject, its Transform and its StandablePlatform, no renderer or masonry");
                StringAssert.Contains($"guid: {StandablePlatformGuid}, type: 3", yaml, $"{b.Prefab}: not a StandablePlatform");
                Assert.AreEqual(b.Id, PrefabField(yaml, "_id"), $"{b.Prefab}: another bridge's id");
                Match fp = Regex.Match(yaml, @"\n  _footprint:\n    serializedVersion: 2\n    x: (\S+)\n    y: (\S+)\n    width: (\S+)\n    height: (\S+)\n");
                Assert.IsTrue(fp.Success, $"{b.Prefab}: no footprint");
                var rect = new Rect(Num(fp.Groups[1].Value), Num(fp.Groups[2].Value), Num(fp.Groups[3].Value), Num(fp.Groups[4].Value));
                Assert.AreEqual(b.Footprint, rect, $"{b.Prefab}: not the network's footprint");
                Assert.AreEqual(b.Deck, Num(PrefabField(yaml, "_deckElevation")), 1e-4f, $"{b.Prefab}: not the network's deck");
                Match at = Regex.Match(yaml, @"\n  m_LocalPosition: \{x: (\S+), y: (\S+), z: 0\}");
                Assert.IsTrue(at.Success, $"{b.Prefab}: no position");
                Assert.That(Vector2.Distance(rect.center, new Vector2(Num(at.Groups[1].Value), Num(at.Groups[2].Value))), Is.LessThan(1e-3f),
                    $"{b.Prefab}: not stood at its footprint's centre");
                Assert.That(b.Deck, Is.GreaterThan(SpringHigh), $"{b.Id}: the deck is under spring high water");
                // on its edge counts: an end can stand on the footprint's far side, which Rect.Contains leaves open
                Assert.That(Mathf.Max(NineMileCreekRoadNetwork.PointToRect(b.A, rect), NineMileCreekRoadNetwork.PointToRect(b.B, rect)), Is.LessThan(1e-3f),
                    $"{b.Id}: its footprint does not hold both its ends");
            }
        }

