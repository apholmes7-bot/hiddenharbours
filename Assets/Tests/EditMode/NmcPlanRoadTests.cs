        [Test]
        public void NoRoadFordsAWater_EveryCarriagewayIsDryOffItsDecks()
        {
            Assert.AreEqual(0, Net.Fords, "the network lists a ford");
            var ground = NineMileCreekGround.Load();
            ushort[] still = NineMileCreekGroundMasks.ReadGround().Still;
            string FirstWet(NineMileCreekRoadNetwork.Route r)
            {
                for (int i = 1; i < r.Points.Length; i++)
                {
                    Vector2 a = r.Points[i - 1], b = r.Points[i], u = (b - a).normalized, n = new Vector2(-u.y, u.x);
                    float len = (b - a).magnitude;
                    for (float s = 0f; s <= len; s += 0.5f)
                        foreach (float o in new[] { -r.HalfWidth, 0f, r.HalfWidth })
                        {
                            Vector2 q = a + u * s + n * o;
                            if (Net.Bridges.Any(d => d.Footprint.Contains(q))) continue;
                            int t = NineMileCreekGroundMasks.TexelOf(q.x, q.y);
                            if (ground.ElevationAt(q) <= SpringHigh || (t >= 0 && t < still.Length && still[t] != 0))
                                return $"{r} at ({q.x:0.##}, {q.y:0.##})";
                        }
                }
                return null;
            }
            var wet = Net.Routes.Concat(Net.Flares).Where(r => RoadClasses.Contains(r.Class)).Select(FirstWet).Where(w => w != null).ToList();
            CollectionAssert.IsEmpty(wet, "a carriageway or a corner flare stands in water outside a deck's footprint (a ford)");
        }

        static string PrefabField(string yaml, string key)
        {
            Match m = Regex.Match(yaml, "\n  " + key + ": (.*)\n");
            Assert.IsTrue(m.Success, $"the prefab has no {key}");
            return m.Groups[1].Value.Trim();
        }

        static float Num(string text) => float.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture);

        [Test]
        public void EachDeck_IsAPlainStandablePrefab_OfItsFootprintAndHeight()
        {
            CollectionAssert.AreEquivalent(
                new[] { "bridge.nmc_route91_river", "bridge.nmc_camp_brook_bridge", "bridge.nmc_camp_pond_culvert" },
                Net.Bridges.Select(b => b.Id), "Q7: the three decks H4 builds");
